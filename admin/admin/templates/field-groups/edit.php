    'repeater'     => 'Repeating rows',
];

// A GLYPH PER TYPE, for the summary row, beside the type name: it is what makes
// the field table scannable — at a glance you see the SHAPE of the group — four
// text rows and a repeater — without reading a word. Keyed off the same list
// above, so a type with no entry simply gets the
// text glyph rather than an invisible control.
$typeIcons = [
    'text'         => 'pen',
    'textarea'     => 'align-left',
    'rich_text'    => 'align-justify',
    'number'       => 'hashtag',
    'date'         => 'calendar',
    'datetime'     => 'clock',
    'select'       => 'caret-down',
    'image'        => 'image',
    'relationship' => 'link',
    'taxonomy'     => 'tags',
    'repeater'     => 'table-list',
];

// Sub-fields are a deliberately SMALLER vocabulary. A repeater inside a repeater
// has no renderer and no name shape that round-trips, and `image`/`relationship`
// /`taxonomy` inside one are unbuilt rather than forbidden — offering them here
// would be offering a control that posts nowhere.
$subFieldTypes = [
    'text'      => 'Text',
    'textarea'  => 'Text area',
    'rich_text' => 'Long text',
    'number'    => 'Number',
    'date'      => 'Date',
    'datetime'  => 'Date and time',
    'select'    => 'Choice',
];

$action = $isNew
    ? Url::admin('field-groups/new')
    : Url::admin('field-groups/' . $id . '/edit');

/**
 * ONE FIELD ROW. Called for the stored rows below AND written into a <template>
 * for the Add-field button, so the markup exists once. A row built by JS from a
 * string literal is a second copy of this form that drifts the first time a
 * setting is added — which is exactly how a field type ends up editable on
 * existing rows and not on new ones.
 *
 * `$i` is the POST index. The template's rows carry `__I__`, which the script
 * substitutes; every name is rebuilt from scratch on add and remove anyway, so a
 * gap in the numbering is harmless — `validateAndSanitize()` iterates values.
 */
$renderRow = static function (
    string $i,
    array $row,
    array $fieldTypes,
    array $typeIcons,
    array $subFieldTypes,
    callable $optionsText,
    array $allContentTypes,
    ?string $error
) use (&$renderSubRow): string {
    ob_start();
    $n = 'fields[' . $i . ']';
    $s = $n . '[settings]';

    $type     = (string) $row['type'];
    $settings = (array) $row['settings'];
    $logic    = \Cms\Forms\Logic::parse($settings['logic'] ?? null);
    ?>
    <div class="fgrow is-collapsed" data-field-row>

        <?php // ── THE SUMMARY BAR ──────────────────────────────────────────
              // `# | Label | Name | Type` — a field table. Drawn
              // permanently open as a three-input grid, a group with five
              // fields would be a wall of identical boxes: you could not see
              // the group's shape, could not find a field by name, and would
              // scroll past every setting of every field to reach the last
              // one.
              //
              // The bar is DERIVED. Its label, name and type are written by
              // field-group-form.js from the inputs in the body below, so the
              // collapsed view can never disagree with what will be saved. ?>
        <div class="fgrow__bar">
            <?php // THE HANDLE, AND IT IS A REAL ONE. The order of fields IS the
                  // order of the entry form, so a row is moved by dragging it
                  // rather than by deleting a field and adding it again at the
                  // end. ?>
            <?php // THE TIP SITS ON THE GRIP, NOT ON THE HANDLE. The handle also
                  // holds the row's index, which is visible text — and the rule
                  // is absolute: an element with its own visible label does not
                  // get a tooltip. The grip alone is glyph-only, which is
                  // exactly what a tip is allowed on. ?>
            <?php // NOT focusable and not a button: there is no
                  // keyboard reorder, and a control that takes focus and then
                  // does nothing with it is worse than one that does not. ?>
            <span class="fgrow__handle" data-field-grab
                  aria-label="Reorder this field">
                <span class="fgrow__grip-wrap" data-tip="Drag to reorder">
                    <?= icon('grip-vertical', 'fgrow__grip icon icon--sm') ?>
                </span>
                <span class="fgrow__num" data-row-num></span>
            </span>

            <button type="button" class="fgrow__grab" data-field-toggle
                    aria-expanded="false">
                <span class="fgrow__caret"><?= icon('angle-down', 'icon icon--sm') ?></span>
                <span class="fgrow__label" data-row-label></span>
                <span class="fgrow__name" data-row-name></span>
                <span class="fgrow__type">
                    <span data-row-type-icon><?= icon($typeIcons[$type] ?? 'pen', 'icon icon--sm') ?></span>
                    <span data-row-type></span>
                </span>
            </button>

            <span class="fgrow__flags">
                <span class="tag" data-row-req hidden>Required</span>
                <span class="tag" data-row-logic hidden>Logic</span>
            </span>

            <?php // A CONTROL, NOT A HINT. A bare `×` in the faintest ink the
                  // theme has, at the far right of a row whose other five
                  // columns are also quiet, is a delete button you have to hunt
                  // for. `--outline` gives it the 1px box every other control
                  // on the screen has, so it reads as a thing you press. No
                  // alert colour: --danger stays on the confirm dialog this
                  // opens, never on the trigger.
                  //
                  // Glyph-only, so a tooltip is allowed. ?>
            <button type="button" class="icon-btn icon-btn--outline" data-field-remove
                    data-tip="Delete this field" aria-label="Delete this field">
                <?= icon('trash-can', 'icon icon--sm') ?>
            </button>
        </div>

        <?php if ($error !== null): ?>
            <?php // `.alert-flag` — the inline badge form of the alert surface,
                  // for a dense row. A bare red line would be red text on
                  // ordinary chrome, and alert colour is a SURFACE, never a
                  // state.
                  //
                  // OUTSIDE the collapsed body on purpose: a row that failed
                  // validation has to say so while it is shut, or the alert at
                  // the top of the page names a field you cannot find. ?>
            <p class="fgrow__error">
                <span class="alert-flag">
                    <?= icon('triangle-exclamation', 'icon', '', 11) ?><?= h($error) ?>
                </span>
            </p>
        <?php endif; ?>

        <div class="fgrow__body">

            <?php // ── THE TAB STRIP ────────────────────────────────────────
                  // Four tabs. It is not decoration: a field
                  // has four unrelated kinds of setting, and a single column of
                  // twelve controls makes "where do I set the instructions"
                  // a hunt every time. ?>
            <?php // `.tabs` — admin.css's own component, whose rule is "a
                  // background swap, never a coloured underline", rather than a
                  // second tab class with an underline. ?>
            <?php // EACH TAB WEARS ITS OWN MARK. Four bare words in a row, three
                  // of them in the quiet register, is a strip you read rather
                  // than glance at — and the four are unrelated KINDS of setting,
                  // which is exactly the case where a repeated word is a glyph
                  // waiting to happen. The marks are the ones the rest of
                  // the admin already uses for the same ideas: the pen for the
                  // thing you name, the shield for what is enforced, the layout
                  // mark for where it sits, the branch for a rule. ?>
            <div class="tabs" role="tablist" aria-label="Field settings">
                <button type="button" class="tabs__tab is-active" role="tab"
                        aria-selected="true" data-fgtab="general"><?= icon('pen', 'icon icon--sm') ?>General</button>
                <button type="button" class="tabs__tab" role="tab"
                        aria-selected="false" data-fgtab="validation"><?= icon('shield-halved', 'icon icon--sm') ?>Validation</button>
                <button type="button" class="tabs__tab" role="tab"
                        aria-selected="false" data-fgtab="presentation"><?= icon('table-columns', 'icon icon--sm') ?>Presentation</button>
                <button type="button" class="tabs__tab" role="tab"
                        aria-selected="false" data-fgtab="logic"><?= icon('folder-tree', 'icon icon--sm') ?>Conditional logic</button>
            </div>

            <?php // ── GENERAL ──────────────────────────────────────────── ?>
            <div class="fgpane" data-fgpane="general">
                <?php // TYPE · LABEL · NAME, ON ONE ROW. These are the three
                      // facts that identify a field — they are the three columns
                      // of the collapsed row above, and they are read together.
                      //
                      // A lone select on its own line above a two-column row
                      // would be one 320px control with 600px of nothing beside
                      // it, then two equal halves under it: two rows, three
                      // different widths, nothing lining up with anything. Full
                      // width is no better — a fourteen-option enum in an 800px
                      // box reads as somewhere to type a sentence. One even grid
                      // answers both. ?>
                <div class="form-grid form-grid--3">
                    <div class="field">
                        <label class="label">Field type</label>
                        <select class="select" name="<?= h($n) ?>[type]" data-field-type>
                            <?php foreach ($fieldTypes as $value => $label): ?>
                                <option value="<?= h($value) ?>"<?= $type === $value ? ' selected' : '' ?>>
                                    <?= h($label) ?>
                                </option>
                            <?php endforeach; ?>
                        </select>
                        <p class="form-help">What the visitor fills in.</p>
                    </div>

                    <div class="field">
                        <label class="label">Field label</label>
                        <input class="input" type="text" name="<?= h($n) ?>[label]"
                               value="<?= h((string) $row['label']) ?>" autocomplete="off"
                               placeholder="Start date" data-field-label>
                        <p class="form-help">The heading above this field on the entry form.</p>
                    </div>

                    <div class="field">
                        <label class="label">Field name</label>
                        <?php // Derived from the label by the script until someone
                              // types in it, then left alone — the key is what
                              // post_meta rows are stored under, so re-deriving it
                              // after an edit would orphan every value already
                              // saved. The server derives it too when the box is
                              // empty; this is a preview of that, not a second
                              // rule. ?>
                        <input class="input input--mono" type="text" name="<?= h($n) ?>[key]"
                               value="<?= h((string) $row['key']) ?>" autocomplete="off"
                               placeholder="start_date" data-field-key>
                        <p class="form-help">Lowercase, no spaces. Underscores are fine.</p>
                    </div>
                </div>

                <?php // ── THE TYPE-SPECIFIC SETTINGS ────────────────────────
                      // All of them, always in the DOM, revealed by type.
                      // `hidden` here is the SERVER's opening position;
                      // field-group-form.js owns it afterwards and DISABLES what
                      // it hides, so nothing posts from a panel that no longer
                      // applies. Hidden-but-enabled would mean changing a choice
                      // field to a number and saving would keep writing the old
                      // options list forever. ?>

                <div class="fields__settings" data-for="textarea rich_text"
                     <?= in_array($type, ['textarea', 'rich_text'], true) ? '' : 'hidden' ?>>
                    <div class="field field--narrow">
                        <label class="label">Rows</label>
                        <input class="input" type="number" min="2" step="1" name="<?= h($s) ?>[rows]"
                               value="<?= h((string) ($settings['rows'] ?? '')) ?>" placeholder="4">
                    </div>
                </div>

                <div class="fields__settings" data-for="number"
                     <?= $type === 'number' ? '' : 'hidden' ?>>
                    <div class="form-grid form-grid--2">
                        <div class="field">
                            <label class="label">Minimum</label>
                            <input class="input" type="number" name="<?= h($s) ?>[min]"
                                   value="<?= h((string) ($settings['min'] ?? '')) ?>">
                        </div>
                        <div class="field">
                            <label class="label">Maximum</label>
                            <input class="input" type="number" name="<?= h($s) ?>[max]"
                                   value="<?= h((string) ($settings['max'] ?? '')) ?>">
                        </div>
                    </div>
                </div>

                <div class="fields__settings" data-for="select"
                     <?= $type === 'select' ? '' : 'hidden' ?>>
                    <div class="field">
                        <label class="label">Choices</label>
                        <textarea class="textarea input--mono" rows="4"
                                  name="<?= h($s) ?>[options_text]"
                                  placeholder="Small&#10;Medium&#10;large : Large"><?= h($optionsText($settings)) ?></textarea>
                        <p class="form-help">
                            One per line. <code>value : Label</code> to store something
                            different from what is shown; a line on its own is both.
                        </p>
                    </div>
                </div>

                <div class="fields__settings" data-for="relationship"
                     <?= $type === 'relationship' ? '' : 'hidden' ?>>
                    <div class="field">
                        <label class="label">Links to</label>
                        <?php
                        $target = (string) ($settings['content_type_target']
                            ?? $settings['post_type_target'] ?? '');
                        ?>
                        <select class="select" name="<?= h($s) ?>[content_type_target]">
                            <option value="">Choose a content type</option>
                            <?php foreach ($allContentTypes as $ct): ?>
                                <option value="<?= h((string) $ct['key']) ?>"<?= $target === $ct['key'] ? ' selected' : '' ?>>
                                    <?= h((string) $ct['label']) ?>
                                </option>
                            <?php endforeach; ?>
                        </select>
                    </div>
                </div>

                <div class="fields__settings" data-for="taxonomy"
                     <?= $type === 'taxonomy' ? '' : 'hidden' ?>>
                    <?php
                    $taxKey  = (string) ($settings['taxonomy_key'] ?? '');
                    $taxMode = (string) ($settings['field_mode'] ?? 'select');
                    $taxes   = TaxonomyRegistry::all();
                    ?>
                    <?php if ($taxes === []): ?>
                        <?php // SHOW THE OBSTACLE, not an empty dropdown. A select
                              // with no options reads as "loading" or "broken";
                              // this says which screen fixes it. ?>
                        <p class="form-help">
                            No taxonomies are registered yet, so this field would have
                            nothing to offer.
                            <a class="link" href="<?= h(Url::admin('taxonomies/new')) ?>">Add a taxonomy</a>
                            first.
                        </p>
                    <?php else: ?>
                        <div class="form-grid form-grid--2">
                            <div class="field">
                                <label class="label">Taxonomy</label>
                                <select class="select" name="<?= h($s) ?>[taxonomy_key]">
                                    <option value="">Choose a taxonomy</option>
                                    <?php foreach ($taxes as $tax): ?>
                                        <option value="<?= h((string) $tax['key']) ?>"<?= $taxKey === $tax['key'] ? ' selected' : '' ?>>
                                            <?= h((string) $tax['label']) ?>
                                        </option>
                                    <?php endforeach; ?>
                                </select>
                            </div>
                            <div class="field">
                                <label class="label">Shown as</label>
                                <select class="select" name="<?= h($s) ?>[field_mode]">
                                    <option value="select"<?= $taxMode === 'select' ? ' selected' : '' ?>>A dropdown</option>
                                    <option value="checkbox"<?= $taxMode === 'checkbox' ? ' selected' : '' ?>>Tick boxes</option>
                                    <option value="radio"<?= $taxMode === 'radio' ? ' selected' : '' ?>>A single choice</option>
                                </select>
                            </div>
                        </div>
                        <label class="check-list__row">
                            <input type="checkbox" name="<?= h($s) ?>[multiple]" value="1"
                                   <?= !empty($settings['multiple']) ? 'checked' : '' ?>>
                            <span>More than one term can be chosen</span>
                        </label>
                    <?php endif; ?>
                </div>

                <div class="fields__settings" data-for="repeater"
                     <?= $type === 'repeater' ? '' : 'hidden' ?>>
                    <label class="label">Rows contain</label>
                    <?php // EDITABLE, not displayed. FieldGroup::update() deletes
                          // every field row and re-inserts from the POST, so a
                          // sub-field this form does not render is a sub-field the
                          // next save destroys. ?>
                    <div class="subfields" data-subfields>
                        <?php foreach ((array) ($settings['sub_fields'] ?? []) as $j => $sub): ?>
                            <?= $renderSubRow($i, (string) $j, (array) $sub, $subFieldTypes, $optionsText) ?>
                        <?php endforeach; ?>
                    </div>
                    <div class="form-actions form-actions--bare">
                        <button type="button" class="btn btn--sm" data-subfield-add>Add a column</button>
                    </div>
                </div>
            </div>

            <?php // ── VALIDATION ───────────────────────────────────────── ?>
            <div class="fgpane" data-fgpane="validation" hidden>
                <label class="check-list__row">
                    <input type="checkbox" name="<?= h($n) ?>[required]" value="1"
                           <?= !empty($row['required']) ? 'checked' : '' ?> data-field-required>
                    <span>This field must be filled in</span>
                </label>

                <div class="field">
                    <label class="label">Message when it is left blank</label>
                    <input class="input" type="text" name="<?= h($s) ?>[msg_required]"
                           value="<?= h((string) ($settings['msg_required'] ?? '')) ?>"
                           placeholder="This field is required." autocomplete="off">
                    <p class="form-help">
                        Leave blank for the standard wording.
                    </p>
                </div>
            </div>

            <?php // ── PRESENTATION ─────────────────────────────────────── ?>
            <div class="fgpane" data-fgpane="presentation" hidden>
                <div class="field">
                    <label class="label">Instructions</label>
                    <textarea class="textarea" rows="2"
                              name="<?= h($s) ?>[instructions]"><?= h((string) ($settings['instructions'] ?? '')) ?></textarea>
                    <p class="form-help">
                        Shown under the field on the entry form, for anything that
                        needs explaining.
                    </p>
                </div>

                <div class="field field--narrow">
                    <label class="label">Width</label>
                    <?php // THE SAME LIST THE FORM BUILDER OFFERS —
                          // `Ui\FieldWidth`. Two hand-typed <option> pairs is
                          // how one surface ends up offering a width the other
                          // has never heard of. ?>
                    <?php $width = \Cms\Ui\FieldWidth::normalize($settings['width'] ?? null); ?>
                    <select class="select" name="<?= h($s) ?>[width]">
                        <?php foreach (\Cms\Ui\FieldWidth::labels() as $value => $label): ?>
                            <option value="<?= h($value) ?>"<?= $width === $value ? ' selected' : '' ?>>
                                <?= h($label) ?>
                            </option>
                        <?php endforeach; ?>
                    </select>
                </div>
            </div>

            <?php // ── CONDITIONAL LOGIC ────────────────────────────────────
                  // ONE HIDDEN INPUT CARRYING JSON, not a nest of
                  // `settings[logic][rules][0][op]` names. A rule list is a
                  // nested array of unknown length; expressing that in form
                  // field names gives you something nobody can read, nobody can
                  // debug, and PHP silently reindexes on the way in. The form
                  // builder posts its whole field list the same way for the same
                  // reason, and `Logic::parse()` is the one thing that reads it. ?>
