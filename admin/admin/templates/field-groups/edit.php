/**
 * THE FIELD GROUP EDITOR — one screen, create and edit both.
 *
 * This is where a Content Type's fields are edited. An archetype only starts
 * them: tick `Event` on the type form and the controller generates a group.
 * That is a starting shape; adding one field to it happens here, not in the
 * database.
 *
 * ── SAME LAYOUT AS EVERY OTHER FORM ─────────────────────────────────────────
 * `.form-main` / `.form-aside`, one `.form-card` per column, sections divided by
 * hairlines, footer as the last section. The entry form, the Pages form, the
 * Content Type form and this one are ONE layout — see core.css §4. Nothing about
 * the geometry is decided in this file.
 *
 * ── THE FIELD EDITOR ────────────────────────────────────────────────────────
 * A field is `label · key · type · required`, plus settings that only some types
 * have. The settings panels are all rendered and CSS-hidden by type, not built
 * in JavaScript, so:
 *
 *   · a field's stored settings are in the DOM whether or not its type is
 *     currently selected — switch a select to a number and back and the options
 *     list is still there;
 *   · nothing depends on JS to be CORRECT. With JS off you get every panel at
 *     once, which is ugly and complete, rather than tidy and lossy.
 *
 * A DISABLED input does not post. That is the mechanism keeping a hidden panel
 * from writing its values into a field that no longer has that type —
 * `field-group-form.js` disables what it hides, exactly as the entry form's
 * password box does. Hidden-but-enabled would mean changing a select field to a
 * number and saving would keep writing the old options list forever.
 *
 * ── REPEATER SUB-FIELDS ARE EDITABLE HERE, AND THEY HAVE TO BE ──────────────
 * `FieldGroup::update()` DELETES every field row and re-inserts from the POST.
 * So anything this form does not render, it destroys on the next save. A
 * repeater whose sub-fields were merely displayed — or not displayed at all —
 * would come back empty the first time someone renamed the group. That is not a
 * missing feature, it is data loss, which is why the nested editor is here.
 *
 * ── WHAT IS DELIBERATELY NOT HERE ───────────────────────────────────────────
 * `sort_order` on the GROUP has no control. It orders groups against each other
 * on an entry form and the only sensible way to set it is by dragging the list
 * — a control that is a number box for "which group comes first" asks the owner
 * to hold the whole ordering in their head. `FieldGroup::update()` defaults it
 * to 0 when absent, so the value is preserved by a hidden input rather than
 * silently reset.
 *
 * @var array<string, mixed>|null  $group            null on create
 * @var array<string, mixed>       $formData         $_POST on a failed submit
 * @var array<string, string>      $errors           keyed: 'title', 'field_<i>'
 * @var array<string, array>       $allContentTypes  Registry::all()
 * @var bool                       $saved            handleUpdate() only
 */

$saved    = $saved    ?? false;
$errors   = $errors   ?? [];
$formData = $formData ?? [];

$isNew = ($group ?? null) === null;
$id    = $isNew ? 0 : (int) $group['id'];

// On a failed submit the form comes back wearing what the AUTHOR typed, not what
// is in the database — otherwise a validation error silently discards the edit it
// is complaining about. Same rule as the entry form.
$has = $formData !== [];

$title    = (string) ($has ? ($formData['title'] ?? '') : ($group['title'] ?? ''));
$isActive = $has
    ? isset($formData['is_active'])
    : ($isNew ? true : (bool) $group['is_active']);
$targets  = $has
    ? array_values(array_filter((array) ($formData['content_types'] ?? []), 'is_string'))
    : (array) ($group['content_types'] ?? []);
$sortOrder = (int) ($has ? ($formData['sort_order'] ?? 0) : ($group['sort_order'] ?? 0));

// An archetype group was GENERATED by ticking a box on the Content Type form.
// It is a normal, fully editable group — this is a fact about where it came
// from, never a permission. There is no read-only category here.
$isArchetype = !$isNew && !empty($group['is_archetype']);

// ── THE FIELD ROWS, IN ONE SHAPE ────────────────────────────────────────────
// The database hands back DB column names (`field_key`, `field_label`, …) with a
// decoded `settings` array; a failed submit hands back the POST's own shape
// (`key`, `label`, `settings[…]`). Normalising here means the markup below is
// written once instead of branching on which source it came from — the branch
// that would otherwise sit inside every one of the twelve inputs.
$rows = [];

if ($has) {
    foreach ((array) ($formData['fields'] ?? []) as $f) {
        $rows[] = [
            'label'    => (string) ($f['label'] ?? ''),
            'key'      => (string) ($f['key'] ?? ''),
            'type'     => (string) ($f['type'] ?? 'text'),
            'required' => !empty($f['required']),
            'settings' => (array) ($f['settings'] ?? []),
        ];
    }
} elseif (!$isNew) {
    foreach ((array) ($group['fields'] ?? []) as $f) {
        $rows[] = [
            'label'    => (string) $f['field_label'],
            'key'      => (string) $f['field_key'],
            'type'     => (string) $f['field_type'],
            'required' => (bool) $f['is_required'],
            'settings' => (array) $f['settings'],
        ];
    }
}

/**
 * The options textarea's stored form is an assoc array; its edited form is one
 * `value : Label` line per option — the same grammar
 * `FieldGroupController::parseOptions()` reads back. A line with no colon is its
 * own value and label, so the common case ("Small / Medium / Large") needs no
 * punctuation at all.
 */
$optionsText = static function (array $settings): string {
    if (isset($settings['options_text'])) {
        return (string) $settings['options_text'];   // a failed submit's raw text
    }
    $lines = [];
    foreach ((array) ($settings['options'] ?? []) as $value => $label) {
        $lines[] = ((string) $value === (string) $label)
            ? (string) $label
            : $value . ' : ' . $label;
    }
    return implode("\n", $lines);
};

// EVERY TYPE FieldRenderer CAN RENDER, and nothing else. A type offered here
// that the renderer's `match` does not name falls through to its `default` and
